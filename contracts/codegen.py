"""Generate pydantic + TS types from the JSON Schemas in this folder.

Usage:
    uv run python -m contracts.codegen           # write generated files
    uv run python -m contracts.codegen --check   # fail (exit 1) on drift

Outputs (committed, do not edit by hand):
    contracts/gen/pydantic/models.py
    contracts/ext/gen/types.ts
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
PY_OUT = HERE / "gen" / "pydantic" / "models.py"
TS_OUT = HERE / "ext" / "gen" / "types.ts"
HEADER_PY = "# Generated by contracts/codegen.py from contracts/*.schema.json - do not edit.\n"
HEADER_TS = "// Generated by contracts/codegen.py from contracts/*.schema.json - do not edit.\n"

# schema file stem -> exported model name (data-object schemas use the bare type name)
SPECIAL = {"envelope": "Envelope", "ack": "Ack", "meeting-page": "MeetingPage"}


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.replace("-", ".").split(".") if part)


def model_name(stem: str) -> str:
    return SPECIAL.get(stem, pascal(stem))


def schema_files() -> list[Path]:
    return sorted(p for p in HERE.glob("*.schema.json"))


def load_schemas() -> dict[str, dict]:
    return {p.name.removesuffix(".schema.json"): json.loads(p.read_text(encoding="utf-8")) for p in schema_files()}


def _is_nullable(schema: dict) -> bool:
    t = schema.get("type")
    return isinstance(t, list) and "null" in t


def _base_type(schema: dict) -> str | None:
    t = schema.get("type")
    if isinstance(t, list):
        non_null = [x for x in t if x != "null"]
        return non_null[0] if non_null else None
    return t  # type: ignore[return-value]


# ---------------- pydantic ----------------

def py_type(schema: dict, parent: str, prop: str, nested: list[str]) -> str:
    if "const" in schema:
        base = f"Literal[{json.dumps(schema['const'])}]"
        return f"{base} | None" if _is_nullable(schema) else base
    if "enum" in schema:
        vals = ", ".join(json.dumps(v) for v in schema["enum"])
        base = f"Literal[{vals}]"
        return f"{base} | None" if _is_nullable(schema) else base
    t = _base_type(schema)
    if t == "string":
        base = {"uuid": "UUID", "date-time": "datetime"}.get(schema.get("format", ""), "str")
    elif t == "integer":
        base = "int"
    elif t == "number":
        base = "float"
    elif t == "boolean":
        base = "bool"
    elif t == "array":
        inner = py_type(schema.get("items", {}), parent, prop, nested) if schema.get("items") else "Any"
        base = f"list[{inner}]"
    elif t == "object" or "properties" in schema:
        if not schema.get("properties"):
            base = "dict[str, Any]"
        else:
            name = f"{parent}{pascal(prop)}"
            nested.append(py_model(name, schema))
            base = name
    else:
        base = "Any"
    return f"{base} | None" if _is_nullable(schema) else base


def py_model(name: str, schema: dict) -> str:
    props: dict = schema.get("properties", {})
    required = set(schema.get("required", []))
    nested: list[str] = []
    fields: list[str] = []
    for prop, sub in props.items():
        ann = py_type(sub, name, prop, nested)
        if prop in required:
            fields.append(f"    {prop}: {ann}")
        else:
            if " | None" not in ann:
                ann = f"{ann} | None"
            fields.append(f"    {prop}: {ann} = None")
    body = "\n".join(fields) if fields else "    pass"
    model = f"class {name}(BaseModel):\n    model_config = ConfigDict(extra='forbid')\n\n{body}\n"
    return ("\n\n".join(nested) + "\n\n" + model) if nested else model


def gen_pydantic(schemas: dict[str, dict]) -> str:
    chunks = [py_model(model_name(stem), schema) for stem, schema in sorted(schemas.items())]
    imports = (
        "from __future__ import annotations\n\n"
        "from datetime import datetime\n"
        "from typing import Any, Literal\n"
        "from uuid import UUID\n\n"
        "from pydantic import BaseModel, ConfigDict\n"
    )
    return HEADER_PY + imports + "\n\n" + "\n\n".join(c.rstrip() for c in chunks) + "\n"


# ---------------- TypeScript ----------------

def ts_type(schema: dict, parent: str, prop: str, nested: list[str]) -> str:
    if "const" in schema:
        base = json.dumps(schema["const"])
        return f"{base} | null" if _is_nullable(schema) else base
    if "enum" in schema:
        base = " | ".join(json.dumps(v) for v in schema["enum"])
        return f"{base} | null" if _is_nullable(schema) else base
    t = _base_type(schema)
    if t == "string":
        base = "string"
    elif t in ("integer", "number"):
        base = "number"
    elif t == "boolean":
        base = "boolean"
    elif t == "array":
        inner = ts_type(schema.get("items", {}), parent, prop, nested) if schema.get("items") else "unknown"
        base = f"{inner}[]"
    elif t == "object" or "properties" in schema:
        if not schema.get("properties"):
            base = "Record<string, unknown>"
        else:
            name = f"{parent}{pascal(prop)}"
            nested.append(ts_model(name, schema))
            base = name
    else:
        base = "unknown"
    return f"{base} | null" if _is_nullable(schema) else base


def ts_model(name: str, schema: dict) -> str:
    props: dict = schema.get("properties", {})
    required = set(schema.get("required", []))
    nested: list[str] = []
    fields: list[str] = []
    for prop, sub in props.items():
        ann = ts_type(sub, name, prop, nested)
        opt = "" if prop in required else "?"
        fields.append(f"  {prop}{opt}: {ann};")
    body = "\n".join(fields)
    model = f"export interface {name} {{\n{body}\n}}"
    return ("\n\n".join(nested) + "\n\n" + model) if nested else model


def gen_ts(schemas: dict[str, dict]) -> str:
    chunks = [ts_model(model_name(stem), schema) for stem, schema in sorted(schemas.items())]
    return HEADER_TS + "\n" + "\n\n".join(c.rstrip() for c in chunks) + "\n"


def generate() -> dict[Path, str]:
    schemas = load_schemas()
    return {PY_OUT: gen_pydantic(schemas), TS_OUT: gen_ts(schemas)}


def main(argv: list[str] | None = None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    outputs = generate()
    if check:
        drift = [str(p) for p, content in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != content]
        if drift:
            print("codegen drift in: " + ", ".join(drift))
            print("run: uv run python -m contracts.codegen")
            return 1
        print("codegen up to date")
        return 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(HERE.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
